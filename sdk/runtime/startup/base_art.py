#!/usr/bin/env python3
"""The beta startup art ported from the Elekloader migration, as C data for boot_anim.c.

Reads the base's own art (base.json: a compact mark with its tile grid and detached tile, a compact
wordmark, a small font, NEW and BETA, and where each sits) and writes boot_art.h.
final_pixels() is the frame the animation ends on, for the host test and the emulator check. Public
builds keep artwork.json and build.py. Authored data only.
"""
import json
import math
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent


def load():
    return json.loads((HERE / 'base.json').read_text())


def ink(rows, ox=0, oy=0):
    return {(ox + x, oy + y) for y, row in enumerate(rows) for x, c in enumerate(row) if c == '#'}


def text_cells(base, version):
    """Each glyph of NEW and the version: (item, x, y, w, h, pixels) on the screen."""
    if not re.fullmatch(r'\d+\.\d+\.\d+', version):
        raise ValueError('The base version is major.minor.patch')
    font, cells = base['font'], []
    for n, item in enumerate(base['text']):
        string = item['string'].replace('{version}', version)
        width = sum(len(font[c][0]) for c in string) + item['gap'] * (len(string) - 1)
        x = item['x'] - {'left': 0, 'center': width // 2, 'right': width}[item['align']]
        for char in string:
            glyph = font[char]
            cells.append((n, x, item['y'], len(glyph[0]), len(glyph), sorted(ink(glyph, x, item['y']))))
            x += len(glyph[0]) + item['gap']
    return cells


def layers(version):
    base = load()
    m = base['mark']
    mark = ink(m['rows'])
    at, pitch, size = m['tiles']['at'], m['tiles']['pitch'], m['tiles']['size']
    cell = lambda x, y: ((x - at) // pitch, (y - at) // pitch) if (x - at) % pitch < size and (y - at) % pitch < size else None
    tiles = {p for p in mark if cell(*p) in [(gx, gy) for gy in range(3) for gx in range(3) if (gx, gy) != (2, 2)]}
    d = m['disc']
    disc = {(x, y) for x, y in mark if d['x'] <= x < d['x'] + d['w'] and d['y'] <= y < d['y'] + d['h']}
    frame = mark - tiles - disc
    wordmark = ink(base['wordmark']['rows'], base['wordmark']['x'], base['wordmark']['y'])
    cells = text_cells(base, version)
    every = ink(m['rows'], m['x'], m['y']) | wordmark | {p for c in cells for p in c[5]}
    if len(every) != len(mark) + len(wordmark) + sum(len(c[5]) for c in cells):
        raise ValueError('The startup text overlaps the mark or the wordmark')
    if any(not (0 <= x < 128 and 0 <= y < 64) for x, y in every):
        raise ValueError('The startup art leaves the screen')
    return base, (m['x'], m['y']), tiles, disc, frame, cell, cells


def final_pixels(version):
    base, (mx, my), tiles, disc, frame, cell, cells = layers(version)
    return ({(mx + x, my + y) for x, y in tiles | disc | frame} | ink(base['wordmark']['rows'], base['wordmark']['x'], base['wordmark']['y'])
            | {p for c in cells for p in c[5]})


def header(version):
    base, (mx, my), tiles, disc, frame, cell, cells = layers(version)
    size = len(base['mark']['rows'])
    dx0, dy0 = min(x for x, _ in disc), min(y for _, y in disc)
    dw, dh = max(x for x, _ in disc) - dx0 + 1, max(y for _, y in disc) - dy0 + 1
    disc_rows = [sum(1 << (dw - 1 - x) for x in range(dw) if (dx0 + x, dy0 + y) in disc) for y in range(dh)]
    middle = (size - 1) / 2

    # Every pixel of the frame and the eight tiles is a particle that sets off at its own time (ms): the
    # frame clockwise from the top over 300 ms, the tiles from the middle one round the ring, 45 ms apart.
    def phase(x, y):
        return int(math.atan2(x - middle, middle - y) % (2 * math.pi) / (2 * math.pi) * 256) & 255
    ring = ((1, 2, 3), (8, 0, 4), (7, 6, 5))
    turns = sorted((ring[gy][gx], gx, gy) for gy in range(3) for gx in range(3) if (gx, gy) != (2, 2))
    rank = {(gx, gy): n for n, (_, gx, gy) in enumerate(turns)}
    dots = [(mx + x, my + y, phase(x, y) * 300 // 256) for x, y in frame]
    dots += [(mx + x, my + y, 150 + 45 * rank[cell(x, y)]) for x, y in tiles]
    dots.sort(key=lambda d: d[2])
    word = base['wordmark']
    ww, wh = len(word['rows'][0]), len(word['rows'])
    columns = [sum(1 << y for y in range(wh) if word['rows'][y][x] == '#') for x in range(ww)]
    pixels = [p for c in cells for p in c[5]]
    glyphs, first = [], 0
    for item, x, y, w, h, glyph_ink in cells:
        glyphs.append('{%d, %d, %d, %d, %d, %d, %d}' % (item, x, y, w, h, first, len(glyph_ink)))
        first += len(glyph_ink)
    out = ['/* Generated by sdk/runtime/startup/base_art.py from base.json; do not edit. */',
           '#define BOOT_VERSION "%s"' % version,
           '#define BOOT_MID_X %d' % round((mx + size / 2) * 16), '#define BOOT_MID_Y %d' % round((my + size / 2) * 16),
           '#define BOOT_DISC_X %d' % (mx + dx0), '#define BOOT_DISC_Y %d' % (my + dy0),
           '#define BOOT_DISC_W %d' % dw, '#define BOOT_DISC_H %d' % dh,
           '#define BOOT_WORD_X %d' % word['x'], '#define BOOT_WORD_Y %d' % word['y'],
           '#define BOOT_WORD_W %d' % ww, '#define BOOT_WORD_H %d' % wh,
           '#define BOOT_DOTS %d' % len(dots), '#define BOOT_GLYPHS %d' % len(cells),
           'static const uint8_t boot_disc[%d] = {%s};' % (dh, ', '.join(map(str, disc_rows))),
           'struct boot_dot { uint8_t x, y; uint16_t delay; };',
           'static const struct boot_dot boot_dots[%d] = {%s};' % (len(dots), ', '.join('{%d, %d, %d}' % d for d in dots)),
           'static const uint16_t boot_word[%d] = {%s};' % (ww, ', '.join(map(str, columns))),
           'struct boot_glyph { uint8_t item, x, y, w, h; uint16_t first, count; };',
           'static const struct boot_glyph boot_glyph[%d] = {%s};' % (len(cells), ', '.join(glyphs)),
           'static const uint8_t boot_ink[%d][2] = {%s};' % (len(pixels), ', '.join('{%d, %d}' % p for p in pixels))]
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    import sys
    sys.stdout.write(header(sys.argv[1]))
